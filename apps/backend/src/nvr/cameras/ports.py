from __future__ import annotations

from typing import Protocol

from nvr.cameras.domain import Camera, CameraCredentials, ProbeResult, StreamProfile


class CameraRepository(Protocol):
    async def list(self) -> list[Camera]: ...
    async def get(self, camera_id: str) -> Camera | None: ...
    async def get_by_name(self, name: str) -> Camera | None: ...
    async def add(self, camera: Camera) -> None: ...
    async def update(self, camera: Camera) -> None: ...
    async def delete(self, camera_id: str) -> None: ...


class SecretStore(Protocol):
    """Cofre de credenciais de câmeras. Implementações nunca registram os valores em log."""

    def put(self, ref: str, credentials: CameraCredentials) -> None: ...
    def get(self, ref: str) -> CameraCredentials | None: ...
    def delete(self, ref: str) -> None: ...


class StreamProbe(Protocol):
    """Verifica se um perfil da câmera responde (conexão, autenticação, codecs). Somente leitura."""

    async def probe(self, url: str, profile: StreamProfile) -> ProbeResult: ...
